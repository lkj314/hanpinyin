// 历史背景：
//   旧版 Windows SDK 通过 msctf.lib 提供 TSF 接口/类别的 IID_*/CLSID_*/GUID_TFCAT_*
//   符号实体。现代 SDK（10.0.18362 / 10.0.26100）已移除 msctf.lib，仅保留头文件中的
//   `extern const GUID X;` 前向声明（无实体）。因此必须在我们的代码中用 DEFINE_GUID
//   生成实体，否则链接阶段报 LNK2001（未解析的外部符号 IID_ITf...）。
//
// 约定：
//   - 本文件是唯一持有这些 TSF 系统 GUID 实体的 TU（配合 initguid.h）。
//   - 其余 .cpp 通过 <msctf.h> 的 EXTERN_GUID 宏获得 `extern` 声明，与此处定义对应。
//   - IID_IUnknown / IID_IClassFactory 由 uuid.lib 提供，此处不重复定义。
//   - 4 个 HanPinyin 自定义 GUID 在 tsf_guid.cpp 中单独定义，互不冲突。
//
// 数值来源（权威性，依次降级）：
//   1) 本机注册表 HKLM:\SOFTWARE\Classes\Interface\{GUID} 默认名核对（14 项 MATCH）。
//   2) Windows SDK msctf.idl / mingw-w64 / ReactOS 的 uuid(...)（aa80e7f0/f5/f7 等）。
//   3) GUID_PROP_ATTRIBUTE / GUID_TFCAT_TIP_KEYBOARD 采用 Windows SDK 公开常量值。

